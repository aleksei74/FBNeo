void tms57002_device::execute_run(INT32 cycles)
{
	icount = cycles;
	int ipc = -1;

	while(icount > 0 && !(sti & (S_IDLE | IN_PLOAD /*| IN_CLOAD*/)))
	{
		int iipc;


        if (ipc == -1) {
            // Reuse the first decoded-cache node directly on a matching PC/ST1.
            // No extra cache or state is introduced: collisions, invalidated
            // entries and incomplete nodes use the original decoder unchanged.
            const s16 node = cache.hashbase[pc];
            if (node >= 0 && cache.hashnode[node].st1 == (st1 & ST1_CACHE))
                ipc = cache.hashnode[node].ipc;
            if (ipc == -1) ipc = decode_get_pc();
        }

		iipc = ipc;

		if (sti & (S_READ|S_WRITE))
		{
			if (sti & S_READ)
				xm_step_read();
			else
				xm_step_write();
		}

		macc_read = macc_write;
		macc_write = macc;

		for (;;)
		{
			const icd *i = cache.inst + ipc;

			ipc = i->next;
			switch (i->op)
			{
			case 0:
				goto inst;

			case 1:
				++ca;
				goto inst;

			case 2:
				++id;
				goto inst;

			case 3:
				++ca, ++id;
				goto inst;

#define CINTRPSWITCH
#include "tms57002.hxx"
#undef CINTRPSWITCH

			default:
				bprintf(PRINT_ERROR, _T("Unhandled opcode in tms57002_execute\n"));
				goto inst;
			}
		}
	inst:
		icount--;

		if (rptc)
		{
			rptc--;
			ipc = iipc;
		}
		else if (sti & S_BRANCH)
		{
			sti &= ~S_BRANCH;
			ipc = -1;
		}
		else
		{
			pc++; // Wraps if it reaches 256, next wraps too
			update_pc0();
		}

		if (rptc_next)
		{
			rptc = rptc_next;
			rptc_next = 0;
		}
	}

	if (icount > 0)
		icount = 0;
}

